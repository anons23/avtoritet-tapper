  let last='',lastAt=0;
  function currentRank(){
    const p=Number(String(document.getElementById('points')?.textContent||'0').replace(/[^0-9.]/g,''))||0;
    if(p>=25000)return 'Вор в законе';
    if(p>=8000)return 'Авторитет';
    if(p>=2000)return 'Смотрящий';
    if(p>=500)return 'Блатной';
    if(p>=100)return 'Мужик';
    return 'Лох';
  }
  function pick(rank){
    const pool=STORIES[rank]||STORIES['Лох'];
    let item=pool[Math.floor(Math.random()*pool.length)];
    if(pool.length>1)while(item===last)item=pool[Math.floor(Math.random()*pool.length)];
    last=item;lastAt=Date.now();return item;
  }
  function replaceGeneric(){
    const el=document.getElementById('event-message');
    if(!el||!el.classList.contains('show'))return;
    const text=el.textContent||'';
    if(OLD_GENERIC.indexOf(text)<0)return;
    el.textContent=pick(currentRank());
  }
  function scheduled(){
    if(document.hidden)return;
    const el=document.getElementById('event-message');
    if(!el||el.classList.contains('show'))return;
    if(Date.now()-lastAt<30000)return;
    if(Math.random()>0.55)return;
    if(typeof window.msg==='function')window.msg(pick(currentRank()));
  }
  function init(){
    const el=document.getElementById('event-message');
    if(!el)return;
    new MutationObserver(replaceGeneric).observe(el,{childList:true,characterData:true,subtree:true});
    setInterval(scheduled,9000);
  }
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',init,{once:true});else init();
